"""Score run directories and write JSON, Markdown and charts."""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

import numpy as np

from . import __version__
from .metrics import (
    Event,
    Summary,
    cer_counts,
    final_latency,
    final_text,
    partial_stability,
    time_to_first_partial,
    wer_counts,
)


def load_run(run_dir: str | Path) -> tuple[dict, list[dict]]:
    d = Path(run_dir)
    meta = json.loads((d / "run.json").read_text())
    rows = [json.loads(x) for x in (d / "results.jsonl").read_text().splitlines() if x.strip()]
    return meta, rows


def score_row(row: dict) -> dict:
    """Per-utterance metrics for one result row."""
    events = [Event.from_dict(e) for e in row.get("events", [])]
    hyp = final_text(events)
    wc = wer_counts(row["text"], hyp)
    cc = cer_counts(row["text"], hyp)
    st = partial_stability(events)
    audio_s = row.get("audio_s") or row.get("duration_s")
    compute = row.get("compute_s")
    return {
        "id": row["id"],
        "condition": row["condition"],
        "hyp": hyp,
        "wer_counts": wc,
        "cer_counts": cc,
        "ttfp": time_to_first_partial(events, row["speech_start_s"]),
        "final_lat": final_latency(events, row["speech_end_s"]),
        "flush": None if "done_t" not in row else max(0.0, row["done_t"] - row["stream_end_t"]),
        "rtf": None if compute is None or not audio_s else compute / audio_s,
        "stability": st,
        "error": row.get("error"),
    }


def summarize(scored: list[dict]) -> Summary:
    s = Summary()
    for r in scored:
        if r["error"]:
            continue
        s.n += 1
        s.wer_counts += r["wer_counts"]
        s.cer_counts += r["cer_counts"]
        if not r["hyp"].strip():
            s.empty += 1
        if r["ttfp"] is not None:
            s.ttfp.append(r["ttfp"])
        if r["final_lat"] is not None:
            s.final_lat.append(r["final_lat"])
        if r["flush"] is not None:
            s.flush.append(r["flush"])
        if r["rtf"] is not None:
            s.rtf.append(r["rtf"])
        s.stability += r["stability"]
    return s


def bootstrap_wer_ci(scored: list[dict], iters: int = 1000, seed: int = 0) -> tuple[float, float] | None:
    ok = [r for r in scored if not r["error"]]
    if len(ok) < 5:
        return None
    errs = np.array([r["wer_counts"].errors for r in ok], dtype=np.float64)
    refs = np.array([r["wer_counts"].ref_len for r in ok], dtype=np.float64)
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(ok), size=(iters, len(ok)))
    vals = errs[idx].sum(axis=1) / np.maximum(refs[idx].sum(axis=1), 1)
    lo, hi = np.percentile(vals, [2.5, 97.5])
    return float(lo), float(hi)


def build_report(
    run_dirs: list[str | Path], baseline: str | None = None, only: list[str] | None = None
) -> dict:
    providers: dict[str, dict] = {}
    for rd in run_dirs:
        meta, rows = load_run(rd)
        name = meta["provider"]["name"]
        scored = [score_row(r) for r in rows if only is None or r["condition"] in only]
        by_cond: dict[str, list[dict]] = defaultdict(list)
        for r in scored:
            by_cond[r["condition"]].append(r)
        conds = {}
        for cond, items in by_cond.items():
            d = summarize(items).to_dict()
            ci = bootstrap_wer_ci(items)
            d["wer_ci95"] = None if ci is None else [round(ci[0], 4), round(ci[1], 4)]
            d["errors"] = sum(1 for i in items if i["error"])
            conds[cond] = d
        providers[name] = {
            "info": meta["provider"],
            "run": {k: meta[k] for k in ("utterances", "entries", "workers", "tail_s", "paced_real_time",
                                         "machine", "wall_seconds", "errors") if k in meta},
            "conditions": conds,
        }
    first = next(iter(providers.values()))
    cond_order = [c for c in only if c in first["conditions"]] if only else list(first["conditions"])
    base = baseline or cond_order[0]
    return {
        "twb_version": __version__,
        "baseline_condition": base,
        "condition_order": cond_order,
        "providers": providers,
    }


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x * 100:.1f}%"


def _ms(d: dict | None, key: str = "p50_ms") -> str:
    return "n/a" if not d else f"{d[key]:.0f}"


def render_markdown(report: dict) -> str:
    lines = ["# twb report", ""]
    lines.append(f"Generated by telephony-wer-bench {report['twb_version']}. Baseline condition: "
                 f"`{report['baseline_condition']}`.")
    lines.append("")
    for name, p in report["providers"].items():
        info, run = p["info"], p["run"]
        lines += [f"## {name}", ""]
        status = "run on this machine" if info.get("tested", True) else "UNTESTED adapter"
        lines.append(f"{info.get('description', '')} ({status}).")
        lines.append("")
        lines.append(
            f"Sample: {run.get('utterances', '?')} utterances per condition, {run.get('workers', '?')} worker "
            f"process(es), {run.get('machine', {}).get('cpus', '?')} CPUs, "
            f"{'real-time paced' if run.get('paced_real_time') else 'NOT real-time paced (latency is not meaningful)'}."
        )
        lines.append("")
        lines.append("| Condition | Utts | Ref words | WER | 95% CI | CER | First partial p50 (ms) | "
                     "First partial p95 | Final after speech end p50 (ms) | Final p95 | Retraction | Flicker | "
                     "Empty |")
        lines.append("| --- | ---: | ---: | ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |")
        for cond in report["condition_order"]:
            c = p["conditions"].get(cond)
            if not c:
                continue
            ci = c.get("wer_ci95")
            ci_s = "n/a" if not ci else f"{ci[0] * 100:.1f} to {ci[1] * 100:.1f}"
            lines.append(
                f"| {cond} | {c['utterances']} | {c['ref_words']} | {_pct(c['wer'])} | {ci_s} | {_pct(c['cer'])} | "
                f"{_ms(c['time_to_first_partial'])} | {_ms(c['time_to_first_partial'], 'p95_ms')} | "
                f"{_ms(c['final_latency_after_speech_end'])} | "
                f"{_ms(c['final_latency_after_speech_end'], 'p95_ms')} | {_pct(c['retraction_rate'])} | "
                f"{_pct(c['flicker_rate'])} | {c['empty_transcripts']} |"
            )
        lines.append("")
        rtfs = [c["real_time_factor"] for c in p["conditions"].values() if c.get("real_time_factor") is not None]
        if rtfs:
            lines.append(f"Real-time factor (provider compute seconds per audio second), mean over conditions: "
                         f"{sum(rtfs) / len(rtfs):.2f}.")
            lines.append("")
    lines += [
        "## How to read this",
        "",
        "- WER and CER use the normalizer in `docs/metrics.md`, applied to reference and hypothesis.",
        "- The 95% CI comes from resampling utterances 1000 times. With few utterances it is wide. "
        "Differences smaller than the interval are not evidence of a real difference.",
        "- Latencies are wall-clock seconds measured against the audio clock. They depend on the machine, "
        "the number of worker processes and, for hosted providers, the network.",
        "",
    ]
    return "\n".join(lines)


def render_text(report: dict) -> str:
    """Compact fixed-width summary for the terminal."""
    out = []
    for name, p in report["providers"].items():
        run = p["run"]
        flag = "" if p["info"].get("tested", True) else "  [UNTESTED ADAPTER]"
        out.append(f"{name}  ({run.get('utterances', '?')} utterances per condition){flag}")
        out.append(f"  {'condition':<18} {'WER':>6} {'CER':>6} {'1st partial':>12} {'final':>9} {'flicker':>8}")
        for cond in report["condition_order"]:
            c = p["conditions"].get(cond)
            if not c:
                continue
            tt = c["time_to_first_partial"]
            fl = c["final_latency_after_speech_end"]
            out.append(
                f"  {cond:<18} {c['wer'] * 100:>5.1f}% {c['cer'] * 100:>5.1f}% "
                f"{(str(round(tt['p50_ms'])) + ' ms') if tt else 'n/a':>12} "
                f"{(str(round(fl['p50_ms'])) + ' ms') if fl else 'n/a':>9} {c['flicker_rate'] * 100:>7.1f}%"
            )
        out.append("")
    return "\n".join(out).rstrip()


def write_report(report: dict, out_dir: str | Path, charts: bool = True) -> list[Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    paths = []
    p = out / "report.json"
    p.write_text(json.dumps(report, indent=2) + "\n")
    paths.append(p)
    p = out / "report.md"
    p.write_text(render_markdown(report))
    paths.append(p)
    if charts:
        from .plots import plot_latency, plot_wer

        paths.append(plot_wer(report, out / "wer_by_condition.png"))
        paths.append(plot_latency(report, out / "latency_by_condition.png"))
    return paths
